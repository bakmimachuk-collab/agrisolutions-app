const LanguageContext = createContext(null);
const languageStorageKey = "agriplus-language";
const aiLanguageStorageKey = "agriplus-ai-language";
const textProps = new Set(["action", "alt", "aria-label", "label", "note", "placeholder", "text", "title", "eyebrow"]);

function getInitialLanguage() {
  try {
    const saved = window.localStorage.getItem(languageStorageKey);
    return Object.hasOwn(languages, saved) ? saved : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);
  const [aiLanguage, setAiLanguageState] = useState(() => {
    try {
      const saved = window.localStorage.getItem(aiLanguageStorageKey);
      return saved === "app" || Object.hasOwn(languages, saved) ? saved : "app";
    } catch {
      return "app";
    }
  });
  const setLanguage = (nextLanguage) => {
    if (!Object.hasOwn(languages, nextLanguage)) {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    setLanguageState(nextLanguage);
  };
  const setAiLanguage = (nextLanguage) => {
    if (nextLanguage !== "app" && !Object.hasOwn(languages, nextLanguage)) {
      throw new Error(`Unsupported AI response language: ${nextLanguage}`);
    }
    setAiLanguageState(nextLanguage);
  };
  const t = (text) => {
    const leading = text.match(/^\s*/)?.[0] ?? "";
    const trailing = text.match(/\s*$/)?.[0] ?? "";
    const translated = translations[language][text.trim()] ?? text.trim();
    return `${leading}${translated}${trailing}`;
  };

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(languageStorageKey, language);
      window.localStorage.setItem(aiLanguageStorageKey, aiLanguage);
    } catch (error) {
      console.error("Could not save language preferences in this browser.", error);
    }
  }, [language, aiLanguage]);

  const value = useMemo(() => ({ language, setLanguage, aiLanguage, setAiLanguage, t }), [language, aiLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider.");
  return context;
}

function localizeNode(node, t) {
  if (typeof node === "string") {
    if (!node.trim()) return node;
    return t(node);
  }
  if (Array.isArray(node)) return Children.map(node, (child) => localizeNode(child, t));
  if (!isValidElement(node)) return node;

  const props = { ...node.props };
  if (node.props.children !== undefined) {
    props.children = localizeNode(node.props.children, t);
  }
  for (const propName of textProps) {
    if (typeof props[propName] === "string") props[propName] = t(props[propName]);
  }
  return cloneElement(node, props);
}

export function Localize({ children }) {
  const { t } = useLanguage();
  return localizeNode(children, t);
}
